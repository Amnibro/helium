def bounds(cmds):
    xs = []
    ys = []

    def push(x, y):
        xs.append(x)
        ys.append(y)

    for c in cmds:
        op = c[0]
        if op in ("disc", "punch"):
            _, cx, cy, r = c
            push(cx - r, cy - r)
            push(cx + r, cy + r)
        elif op in ("box", "notch"):
            _, x, y, w, h = c
            push(x, y)
            push(x + w, y + h)
        elif op == "tri":
            _, x0, y0, x1, y1, x2, y2 = c
            push(x0, y0)
            push(x1, y1)
            push(x2, y2)
        elif op == "bar":
            _, x0, y0, x1, y1, t = c
            rad = t * 0.5
            push(x0 - rad, y0 - rad)
            push(x0 + rad, y0 + rad)
            push(x1 - rad, y1 - rad)
            push(x1 + rad, y1 + rad)
        elif op == "ring":
            _, cx, cy, r, t = c
            rad = r + t * 0.5
            push(cx - rad, cy - rad)
            push(cx + rad, cy + rad)
    return min(xs), min(ys), max(xs), max(ys)


def fit(cmds, margin=4):
    x0, y0, x1, y1 = bounds(cmds)
    bw = max(1.0, x1 - x0)
    bh = max(1.0, y1 - y0)
    s = min((64 - 2 * margin) / bw, (64 - 2 * margin) / bh)
    dx = (64 - bw * s) / 2 - x0 * s
    dy = (64 - bh * s) / 2 - y0 * s

    def xy(x, y):
        return x * s + dx, y * s + dy

    out = []
    for c in cmds:
        op = c[0]
        if op in ("disc", "punch"):
            _, cx, cy, r = c
            nx, ny = xy(cx, cy)
            out.append((op, nx, ny, r * s))
        elif op in ("box", "notch"):
            _, x, y, w, h = c
            nx, ny = xy(x, y)
            out.append((op, nx, ny, w * s, h * s))
        elif op == "tri":
            _, a, b, c1, d, e, f = c
            a, b = xy(a, b)
            c1, d = xy(c1, d)
            e, f = xy(e, f)
            out.append((op, a, b, c1, d, e, f))
        elif op == "bar":
            _, a, b, c1, d, t = c
            a, b = xy(a, b)
            c1, d = xy(c1, d)
            out.append((op, a, b, c1, d, max(4.0, t * s)))
        elif op == "ring":
            _, cx, cy, r, t = c
            nx, ny = xy(cx, cy)
            out.append((op, nx, ny, r * s, max(3.0, t * s)))
    return out


OPS = {"disc": 1, "box": 2, "tri": 3, "bar": 4, "ring": 5, "punch": 6, "notch": 7}
WIDTH = {"disc": 4, "punch": 4, "box": 5, "notch": 5, "tri": 7, "bar": 6, "ring": 5}


def encode(cmds):
    raw = []
    for c in fit(cmds):
        op = c[0]
        nums = []
        for a in c[1:]:
            v = int(round(a))
            if v < 0:
                v = 0
            if v > 64:
                v = 64
            nums.append(v)
        raw.append(OPS[op])
        raw.extend(nums)
        need = WIDTH[op] - 1
        if len(nums) != need:
            raise SystemExit(f"bad arity {op} {nums}")
    return raw


def emit_batch(batch, icons):
    blobs = [encode(cmds) for _, cmds in icons]
    seen = {}
    for (name, _), blob in zip(icons, blobs):
        key = tuple(blob)
        if key in seen:
            raise SystemExit(f"duplicate geometry {name} == {seen[key]}")
        seen[key] = name
    names = [n for n, _ in icons]
    if len(names) != len(set(names)):
        raise SystemExit("duplicate name")
    ops = []
    at = [0]
    for blob in blobs:
        ops.extend(blob)
        at.append(len(ops))
    lines = []
    lines.append(f"// Named pictograms, batch {batch}. Generated from pictogram_src.py.")
    lines.append("namespace uikit;")
    lines.append("")
    lines.append(f"let ICON_N{batch} = {len(icons)};")
    def chunks(vals, n):
        rows = []
        for i in range(0, len(vals), n):
            rows.append(", ".join(str(v) for v in vals[i:i + n]))
        return rows

    lines.append(f"let ICON_OPS{batch} byte[{len(ops)}] = [")
    op_rows = chunks(ops, 24)
    for i, row in enumerate(op_rows):
        lines.append(f"\t{row}{',' if i + 1 < len(op_rows) else ''}")
    lines.append("];")
    lines.append(f"let ICON_AT{batch} int[{len(at)}] = [")
    at_rows = chunks(at, 16)
    for i, row in enumerate(at_rows):
        lines.append(f"\t{row}{',' if i + 1 < len(at_rows) else ''}")
    lines.append("];")
    lines.append("")
    lines.append(f"fn icon_name_{batch}(i int) const byte[:] {{")
    for i, name in enumerate(names):
        lines.append(f'\tif i == {i} {{ return "{name}"; }}')
    lines.append(f'\t"{names[0]}"')
    lines.append("}")
    lines.append("")
    path = os.path.join(ROOT, f"icons_b{batch}.amni")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {path} icons={len(icons)} bytes={len(ops)}")


def write_reg(nbatches):
    lines = ["// Dispatch for named pictogram batches. Generated from pictogram_src.py.", "namespace uikit;"]
    for b in range(nbatches):
        lines.append(f"import uikit.icons_b{b};")
    lines.append("")
    parts = " + ".join(f"ICON_N{b}" for b in range(nbatches))
    lines.append(f"fn icon_named() int {{ {parts} }}")
    lines.append("")
    lines.append("fn icon_len(id int) int {")
    lines.append("\tif id < 0 || id >= icon_named() { return 0; }")
    for b in range(nbatches):
        prev = "0" if b == 0 else " + ".join(f"ICON_N{i}" for i in range(b))
        if b == 0:
            lines.append("\tif id < ICON_N0 { return ICON_AT0[id + 1] - ICON_AT0[id]; }")
        else:
            lines.append(f"\tif id < {prev} + ICON_N{b} {{")
            lines.append(f"\t\tlet j{b} = id - ({prev});")
            lines.append(f"\t\treturn ICON_AT{b}[j{b} + 1] - ICON_AT{b}[j{b}];")
            lines.append("\t}")
    lines.append("\t0")
    lines.append("}")
    lines.append("")
    lines.append("fn icon_byte(id int, k int) int {")
    lines.append("\tif id < 0 || id >= icon_named() { return 0; }")
    for b in range(nbatches):
        prev = "0" if b == 0 else " + ".join(f"ICON_N{i}" for i in range(b))
        if b == 0:
            lines.append("\tif id < ICON_N0 { return ICON_OPS0[ICON_AT0[id] + k] as int; }")
        else:
            lines.append(f"\tif id < {prev} + ICON_N{b} {{")
            lines.append(f"\t\tlet j{b} = id - ({prev});")
            lines.append(f"\t\treturn ICON_OPS{b}[ICON_AT{b}[j{b}] + k] as int;")
            lines.append("\t}")
    lines.append("\t0")
    lines.append("}")
    lines.append("")
    lines.append("fn icon_name(id int) const byte[:] {")
    lines.append('\tif id < 0 { return "sword"; }')
    for b in range(nbatches):
        prev = "0" if b == 0 else " + ".join(f"ICON_N{i}" for i in range(b))
        if b == 0:
            lines.append("\tif id < ICON_N0 { return icon_name_0(id); }")
        else:
            lines.append(f"\tif id < {prev} + ICON_N{b} {{ return icon_name_{b}(id - ({prev})); }}")
    lines.append('\t"blob"')
    lines.append("}")
    lines.append("")
    path = os.path.join(ROOT, "icons_reg.amni")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {path} batches={nbatches}")


def main():
    names = [n for n, _ in ICONS]
    if len(names) != len(set(names)):
        seen = set()
        for n in names:
            if n in seen:
                raise SystemExit(f"duplicate name {n}")
            seen.add(n)
    if len(ICONS) % 100 != 0:
        raise SystemExit(f"need multiples of 100, have {len(ICONS)}")
    nbatches = len(ICONS) // 100
    for b in range(nbatches):
        emit_batch(b, ICONS[b * 100:(b + 1) * 100])
    write_reg(nbatches)


if __name__ == "__main__":
    main()
